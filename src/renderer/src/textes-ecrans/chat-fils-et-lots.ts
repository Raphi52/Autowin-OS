export type CleChatFilsEtLots = keyof typeof TEXTES_FR

/** Pluriel selon la langue : le français au-delà de 1, l'anglais dès que ce n'est pas 1. */
export const auPluriel = (n: number, langue: Langue): boolean => (langue === 'en' ? n !== 1 : n > 1)

/**
 * Le bilan du plan, dans la langue de l'écran. Les COMPTES viennent de `bilanDuPlan` (le moteur) ;
 * seule la phrase est recomposée ici, et son français est celui du moteur mot pour mot
 * (`ChatFilsEtLots.langue.test.tsx` compare les deux). Le texte du moteur reste en français : l'agent
 * du fil chef le lit aussi.
 */
export function texteDuBilan(plan: PlanDeLots, langue: Langue): string {
  const b = bilanDuPlan(plan)
  const t = (cle: CleChatFilsEtLots, valeurs?: Record<string, string | number>): string =>
    traduireChatFilsEtLots(cle, langue, valeurs)
  const pluriel = (n: number, un: CleChatFilsEtLots, plusieurs: CleChatFilsEtLots): string =>
    t(auPluriel(n, langue) ? plusieurs : un, { n })
  return t('lots.bilan.texte', {
    faits: pluriel(b.faits, 'lots.bilan.faits.un', 'lots.bilan.faits.plusieurs'),
    echecs: b.echecs,
    enCours: b.enCours,
    aFaire: b.aFaire,
    interrompus: b.interrompus
      ? pluriel(b.interrompus, 'lots.bilan.interrompus.un', 'lots.bilan.interrompus.plusieurs')
      : '',
    attendChef: b.attendChef
      ? pluriel(b.attendChef, 'lots.bilan.attendChef.un', 'lots.bilan.attendChef.plusieurs')
      : '',
    total: b.total,
    tours: pluriel(plan.toursLances, 'lots.bilan.tours.un', 'lots.bilan.tours.plusieurs'),
    plafond: plan.plafondTours
  })
}
