/** Identité de casse ordinale Windows, sans expansion Unicode. */
export function foldWindowsOrdinalCase(value: string): string {
  return Array.from(value, (character) => {
    const codePoint = character.codePointAt(0) ?? 0
    if (codePoint > 0xffff) return character
    const override = WINDOWS_ORDINAL_CASE_OVERRIDES.get(codePoint)
    if (override !== undefined) return String.fromCodePoint(override)
    if (/^\p{Lt}$/u.test(character)) return character
    const upper = character.toUpperCase()
    const lower = character.toLowerCase()
    if (Array.from(upper).length !== 1 || Array.from(lower).length !== 1) return character
    return upper.toLowerCase() === lower && lower.toUpperCase() === upper ? upper : character
  }).join('')
}
